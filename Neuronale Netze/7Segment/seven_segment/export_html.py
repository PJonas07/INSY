"""Write the trained model to web/data.js so web/index.html can show it.

A .js file (instead of .json) is used because browsers block fetch() of local files when
index.html is opened directly via double-click (file:// URL); a <script> tag is allowed.
"""

import json
from pathlib import Path

from seven_segment import config
from seven_segment.dataset import SEGMENT_NAMES, SEGMENT_TABLE
from seven_segment.network import NeuralNetwork


def export_model(network: NeuralNetwork, loss_history: list[float], path: Path) -> None:
    """Write weights, loss curve and training data as a JavaScript variable."""
    data = {
        "network": network.to_dict(),
        "lossHistory": loss_history,
        "lossHistoryStep": config.LOSS_HISTORY_STEP,
        "learningRate": config.LEARNING_RATE,
        "segmentNames": list(SEGMENT_NAMES),
        "segmentTable": [list(row) for row in SEGMENT_TABLE],
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    content = (
        "// Generated by seven_segment/export_html.py - do not edit by hand.\n"
        f"window.MODEL_DATA = {json.dumps(data)};\n"
    )
    path.write_text(content, encoding="utf-8")


def main() -> None:
    if not config.MODEL_PATH.exists():
        raise SystemExit("No trained model found. Run 'python -m seven_segment.train' first.")
    network, loss_history = NeuralNetwork.load(config.MODEL_PATH)
    export_model(network, loss_history, config.WEB_DATA_PATH)
    print(f"Wrote {config.WEB_DATA_PATH}")


if __name__ == "__main__":
    main()
