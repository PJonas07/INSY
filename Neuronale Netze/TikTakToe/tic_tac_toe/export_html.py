"""Write the training history to web/data.js so web/index.html can replay it.

A .js file (instead of .json) is used because browsers block fetch() of local files when
index.html is opened directly via double-click (file:// URL); a <script> tag is allowed.
"""

import json
from dataclasses import asdict
from pathlib import Path

import numpy as np

from tic_tac_toe import config
from tic_tac_toe.evaluation import Outcomes
from tic_tac_toe.game import WIN_LINES
from tic_tac_toe.network import NeuralNetwork
from tic_tac_toe.training import Snapshot

# Example position for the self-test of the website: I hold cells 0 and 4, the opponent 1 and 8.
FORWARD_CHECK_INPUTS = [1, -1, 0, 0, 1, 0, 0, 0, -1]


def round_weights(weights: dict[str, list]) -> dict[str, list]:
    """Round every weight and bias, so the file stays small."""
    return {
        name: np.round(np.array(values), config.WEB_DECIMALS).tolist()
        for name, values in weights.items()
    }


def build_forward_check(weights: dict[str, list]) -> dict[str, list]:
    """Compute one example with Python, so the website can test its own JavaScript math."""
    network = NeuralNetwork.from_dict(weights)
    inputs = np.array(FORWARD_CHECK_INPUTS, dtype=float)
    outputs = network.forward(inputs).output_activations
    return {"inputs": FORWARD_CHECK_INPUTS, "outputs": outputs.tolist()}


def export_training(
    snapshots: list[Snapshot],
    outcomes_as_x: Outcomes,
    outcomes_as_o: Outcomes,
    sample_count: int,
    path: Path,
) -> None:
    """Write all snapshots and the playing strength as a JavaScript variable."""
    exported_snapshots = [
        {
            "epoch": snapshot.epoch,
            "loss": snapshot.loss,
            "bestMoveRate": snapshot.best_move_rate,
            "network": round_weights(snapshot.weights),
        }
        for snapshot in snapshots
    ]
    data = {
        "snapshots": exported_snapshots,
        # Uses the rounded weights, because those are the ones the website calculates with.
        "forwardCheck": build_forward_check(exported_snapshots[-1]["network"]),
        "learningRate": config.LEARNING_RATE,
        "sampleCount": sample_count,
        "outcomesAsX": asdict(outcomes_as_x),
        "outcomesAsO": asdict(outcomes_as_o),
        "winLines": [list(line) for line in WIN_LINES],
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    content = (
        "// Generated by tic_tac_toe/export_html.py - do not edit by hand.\n"
        f"window.MODEL_DATA = {json.dumps(data)};\n"
    )
    path.write_text(content, encoding="utf-8")
